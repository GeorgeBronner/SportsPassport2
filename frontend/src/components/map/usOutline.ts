// Equirectangular projection scaled for the mid-US latitude, matching the
// outline above. ViewBox is 946 x 530.
export const MAP_W = 946;
export const MAP_H = 530;
const KX = 0.788 * 20;
const KY = 20;

export const projectX = (lon: number): number => (lon + 126) * KX;
export const projectY = (lat: number): number => (50.6 - lat) * KY;

export const US_PATH =
  US_OUTLINE.map(([lat, lon], i) =>
    `${i === 0 ? 'M' : 'L'}${projectX(lon).toFixed(1)} ${projectY(lat).toFixed(1)}`
  ).join(' ') + ' Z';
